"""Restore an explicitly named current-stage ZIP saved by a prior notebook.

Designed for independent Colab sessions: no historical-file search, recompute,
training, source download, or implicit replacement of existing result files.
"""
from __future__ import annotations

from pathlib import Path
from zipfile import ZipFile


def ensure_stage_inputs(
    output_dir: str | Path, upstream_stage: int,
    required: tuple[str, ...], *, upload_dir: str | Path = "/content",
) -> list[Path]:
    """Reuse current files or restore one explicitly named prior-stage ZIP.

    The archive name is the one generated by the unchanged download helper.
    ZIP members must be ordinary files with safe stage-prefixed flat paths.
    """
    folder = Path(output_dir).resolve()
    folder.mkdir(parents=True, exist_ok=True)
    stage = f"{upstream_stage:02d}"
    required_paths = [folder / name for name in required]
    for name in required:
        if Path(name).name != name or not name.startswith(stage + "_"):
            raise ValueError(f"Expected a flat stage-{stage} filename: {name}")
    if all(p.is_file() for p in required_paths):
        return required_paths
    present = [p.name for p in folder.glob(f"{stage}_*") if p.is_file()]
    if present:
        raise RuntimeError(
            f"Incomplete stage {stage} output set: {present}. Do not mix "
            "partial results with an uploaded archive; inspect the files first."
        )
    archive = Path(upload_dir) / f"{folder.parent.name}_Notebook_{stage}_Outputs.zip"
    if not archive.is_file():
        missing = [p.name for p in required_paths if not p.exists()]
        raise FileNotFoundError(
            f"Missing stage {stage} current outputs: {missing}. If using a new "
            f"Colab runtime, upload the ZIP produced by Notebook {stage} "
            f"to {archive} before running this notebook."
        )
    with ZipFile(archive) as zip_file:
        names = zip_file.namelist()
        if len(set(names)) != len(names):
            raise ValueError(f"Duplicate members in {archive}")
        for entry in zip_file.infolist():
            name = entry.filename
            if (
                entry.is_dir() or not name.startswith(stage + "_")
                or Path(name).name != name or "\\" in name
                or (entry.external_attr >> 16) & 0o170000 == 0o120000
            ):
                raise ValueError(f"Unsafe or unexpected stage ZIP member: {name}")
        if not set(required).issubset(names):
            raise ValueError(f"{archive} does not include all required stage files")
        # All checks precede writes; do not silently overwrite current outputs.
        for entry in zip_file.infolist():
            dest = folder / entry.filename
            if dest.exists():
                raise FileExistsError(f"Refusing to overwrite current output: {dest}")
        for entry in zip_file.infolist():
            dest = folder / entry.filename
            dest.write_bytes(zip_file.read(entry))
    return required_paths
